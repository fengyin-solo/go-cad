// dxf_write_filter.go 在 WriteDXF 全量写出之外提供“按图层子集”写出入口
// （WriteDXFWithOptions + DXFWriteOptions）：
//
// 子集语义（工程交付拆图口径）：
//   - 包含图层（IncludeLayers）非空时为白名单：仅这些图层上的实体会被选中；
//     排除图层（ExcludeLayers）优先级更高，同属包含与排除时按排除处理。
//   - 零层（"0"）恒保留：无需列入包含、列入排除也不生效——零层实体始终选中，
//     LAYER 表的 0 层记录恒存在（DXF 合法底线）。
//   - 名称在写出前一次性校验：包含/排除列表中所有无法解析到文档图层的名字
//     汇总为一个错误返回，写出器不会产生任何字节。
//   - 只写入选中实体：模型空间（含最大块启发式并入内容）、pre-R13 图纸空间、
//     块定义内的实体均按“实体自身（展开前）的图层”逐一判定；父 INSERT 被选中
//     不会把其引用块内位于排除图层上的实体带入。
//   - 块定义只保留“实际可达且仍含选中内容”者：可达性自模型/图纸空间被选中的
//     INSERT 出发，沿块定义层级（嵌套块）遍历；内容判定用最小不动点，纯 INSERT
//     互环、内容全部被滤空的块被剔除；指向被剔除块的选中 INSERT 一并移除，
//     避免输出悬空块引用。
//   - LAYER 表只保留实际被写出实体引用的图层（0 层除外恒在），无实体的图层
//     表项（含列入包含但文档中无实体的图层）不再写出。
//
// 不传选项（nil 或两个列表均空）时直接走 WriteDXF，逐字节保持原行为。
package drawing

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/unitedrhino/go-cad/internal/entity"
)

// DXFWriteOptions DXF 图层子集写出选项。
type DXFWriteOptions struct {
	// IncludeLayers 包含图层名白名单：非空时仅这些图层（及恒保留的零层）
	// 上的实体被选中；为空表示不做白名单限制。
	IncludeLayers []string
	// ExcludeLayers 排除图层名集合：这些图层上的实体一律不写出（零层除外）。
	// 与 IncludeLayers 同时命中某图层时排除优先。
	ExcludeLayers []string
}

// WriteDXFWithOptions 按图层子集选项将文档导出为 ASCII DXF。
// opts 为 nil 或包含/排除列表均空时等价于 WriteDXF（逐字节一致）。
func WriteDXFWithOptions(doc *Document, w io.Writer, opts *DXFWriteOptions) error {
	if doc == nil {
		return errors.New("cad: 文档为空，无法写出 DXF")
	}
	if opts == nil || (len(opts.IncludeLayers) == 0 && len(opts.ExcludeLayers) == 0) {
		return WriteDXF(doc, w)
	}
	plan, err := buildDXFFilterPlan(doc, opts)
	if err != nil {
		return err
	}
	x := &DxfWriter{
		W:     bufio.NewWriter(w),
		alloc: newDXFHandleAlloc(doc),
		verts: plan.verts,
		Doc:   doc,
		plan:  plan,
	}
	x.str(999, "Generated by share/cad WriteDXF (LibreDWG out_dxf aligned)")
	x.writeHeader(doc)
	x.writeTables(doc)
	x.writeBlocks(doc)
	// 模型空间实体（含最大块启发式并入、按图层过滤后的内容）
	x.writeEntities(plan.model, false)
	// pre-R13 图纸空间实体：67=1 标记，按句柄去重（与全量路径同口径）
	if len(plan.pspace) > 0 {
		x.str(0, "SECTION")
		x.str(2, "ENTITIES")
		x.writeEntityList(plan.pspace, true)
		x.str(0, "ENDSEC")
	}
	x.str(0, "EOF")
	x.Err = x.W.Flush()
	return x.Err
}

// dxfFilterPlan 图层子集写出计划：全部为过滤后的最终实体清单，写出侧只消费
// 不再做判定。
type dxfFilterPlan struct {
	model  []any            // ENTITIES 段（模型空间 + 最大块并入内容）
	pspace []any            // pre-R13 图纸空间（已按句柄与模型空间去重）
	blocks map[uint64][]any // 可达且仍含选中内容的块定义（已剔除悬空 INSERT）
	layers []dxfLayerRecord // LAYER 表：0 层 + 实际写出实体引用到的图层
	verts  *dxfVertexIndex  // POLYLINE 顶点聚合索引（与全量写出同源构建）
}

// dxfLayerFilter 图层选择器：按图层句柄判定实体是否选中。
type dxfLayerFilter struct {
	include      map[string]bool // 白名单（空表示不限）
	exclude      map[string]bool // 排除集（优先于白名单）
	nameByHandle map[uint64]string
}

// docLayerName 图层句柄 → 写出侧图层名：与 DxfWriter.layerName 同口径
// （LayerColors 真名优先，缺失时按句柄合成，0 层恒为 "0"）。
func docLayerName(doc *Document, h uint64) string {
	if h == 0 {
		return "0"
	}
	if lc, ok := doc.LayerColors[h]; ok && lc.Name != "" {
		return lc.Name
	}
	return dxfLayerName(h)
}

// keepHandle 图层句柄是否通过过滤。零层恒保留；其余先排除后白名单。
func (f *dxfLayerFilter) keepHandle(h uint64) bool {
	name := f.nameByHandle[h]
	if name == "" {
		name = "0"
	}
	if name == "0" {
		return true
	}
	if f.exclude[name] {
		return false
	}
	if len(f.include) > 0 && !f.include[name] {
		return false
	}
	return true
}

// keepEntity 实体是否按其自身图层选中；取不到公共头的非图元条目一律保留
// （写出侧本就会跳过，不影响块内容判空）。
func (f *dxfLayerFilter) keepEntity(ent any) bool {
	b := entity.EntityBase(ent)
	if b == nil {
		return true
	}
	return f.keepHandle(b.Layer)
}

// buildDXFFilterPlan 执行“名称校验 → 实体过滤 → 块可达性不动点 → 悬空
// INSERT 修剪 → 图层表收集”的完整规划。任何写出动作之前完成，校验失败时
// 返回汇总错误且不触碰 io.Writer。
func buildDXFFilterPlan(doc *Document, opts *DXFWriteOptions) (*dxfFilterPlan, error) {
	// 1. 构建文档图层全集（句柄 → 名）：0 层 + LAYER 表 + 全部实体引用。
	nameByHandle := map[uint64]string{0: "0"}
	note := func(h uint64) {
		if _, ok := nameByHandle[h]; !ok {
			nameByHandle[h] = docLayerName(doc, h)
		}
	}
	for h := range doc.LayerColors {
		note(h)
	}
	for _, list := range [][]any{doc.ModelSpace, doc.PspaceSpace} {
		for _, ent := range list {
			if b := entity.EntityBase(ent); b != nil {
				note(b.Layer)
			}
		}
	}
	for _, list := range doc.Blocks {
		for _, ent := range list {
			if b := entity.EntityBase(ent); b != nil {
				note(b.Layer)
			}
		}
	}

	// 2. 一次性校验包含/排除名称：未知名字去重汇总，稳定排序后一次报错。
	known := map[string]bool{}
	for _, name := range nameByHandle {
		known[name] = true
	}
	seen := map[string]bool{}
	var unknown []string
	checkNames := func(names []string) {
		for _, raw := range names {
			name := strings.TrimSpace(raw) // 空串不在 known 中，自然计入未知
			if seen[name] {
				continue
			}
			seen[name] = true
			if !known[name] {
				unknown = append(unknown, name)
			}
		}
	}
	checkNames(opts.IncludeLayers)
	checkNames(opts.ExcludeLayers)
	if len(unknown) > 0 {
		sort.Strings(unknown)
		return nil, fmt.Errorf("cad: DXF 图层子集写出失败，未知图层: %s", strings.Join(unknown, ", "))
	}

	f := &dxfLayerFilter{
		include:      nameSet(opts.IncludeLayers),
		exclude:      nameSet(opts.ExcludeLayers),
		nameByHandle: nameByHandle,
	}

	largest := doc.LargestBlockHeader()
	pseudo := dxfPseudoBlockKeys(doc)
	// normalBlockKey 判定普通块定义（全量写出会在 BLOCKS 段输出者）：
	// 最大块启发式块与 POLYLINE 伪块不在其列。
	normalBlock := func(h uint64) bool {
		if h == largest || pseudo[h] {
			return false
		}
		_, ok := doc.Blocks[h]
		return ok
	}

	// 3. 逐条实体列表按实体自身图层过滤。模型空间池与全量写出同源
	// （直属 + 最大块并入），但 largest 只取一次：LargestBlockHeader
	// 在等大区块上随 map 遍历序变动，池并入与 BLOCKS 段排除必须使用同一
	// 决策，否则同一块可能既进 ENTITIES 又出 BLOCKS 定义（句柄重复）。
	filterList := func(list []any) []any {
		out := make([]any, 0, len(list))
		for _, ent := range list {
			if f.keepEntity(ent) {
				out = append(out, ent)
			}
		}
		return out
	}

	msBase := make([]any, 0, len(doc.ModelSpace))
	msBase = append(msBase, doc.ModelSpace...)
	if largest != 0 {
		msBase = append(msBase, doc.Blocks[largest]...)
	}
	msPool := filterList(msBase)
	psPool := filterList(doc.PspaceSpace)

	// 普通块定义：图层过滤后的候选内容（仅保留确有可输出实体者）。
	filteredBlocks := map[uint64][]any{}
	for h, list := range doc.Blocks {
		if !normalBlock(h) {
			continue
		}
		fl := filterList(list)
		if len(dxfEmitSelection(fl)) > 0 {
			filteredBlocks[h] = fl
		}
	}

	// 4. 可达性：自模型/图纸空间被选中的 INSERT 出发，沿块定义层级遍历。
	reachable := map[uint64]bool{}
	var stack []uint64
	noteTarget := func(h uint64) {
		if !normalBlock(h) || reachable[h] {
			return
		}
		reachable[h] = true
		stack = append(stack, h)
	}
	noteRoots := func(list []any) {
		for _, ent := range dxfEmitSelection(list) {
			if ins, ok := ent.(*entity.EntInsert); ok {
				noteTarget(ins.BlockHeader)
			}
		}
	}
	noteRoots(msPool)
	noteRoots(psPool)
	for len(stack) > 0 {
		h := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		for _, ent := range dxfEmitSelection(filteredBlocks[h]) {
			if ins, ok := ent.(*entity.EntInsert); ok {
				noteTarget(ins.BlockHeader)
			}
		}
	}

	// 5. “仍含选中内容”最小不动点：非 INSERT 的可输出实体直接算数；
	// INSERT 仅当引用的普通块在集合内时算数。自空集向上迭代——纯 INSERT
	// 互环没有任何实质内容，不会自举，正确剔除。
	kept := map[uint64]bool{}
	effective := func(h uint64, set map[uint64]bool) bool {
		for _, ent := range dxfEmitSelection(filteredBlocks[h]) {
			if ins, ok := ent.(*entity.EntInsert); ok && normalBlock(ins.BlockHeader) {
				if set[ins.BlockHeader] {
					return true
				}
				continue
			}
			return true
		}
		return false
	}
	for {
		added := false
		for h := range reachable {
			if kept[h] {
				continue
			}
			if effective(h, kept) {
				kept[h] = true
				added = true
			}
		}
		if !added {
			break
		}
	}

	// 6. 修剪悬空 INSERT：引用普通块但该块未保留（滤空/不可达/互环）的
	// INSERT 不写出，避免块引用无定义。其余目标（最大块/伪块/未知块）
	// 保持全量写出口径不动。
	prune := func(list []any) []any {
		out := make([]any, 0, len(list))
		for _, ent := range dxfEmitSelection(list) {
			if ins, ok := ent.(*entity.EntInsert); ok && normalBlock(ins.BlockHeader) && !kept[ins.BlockHeader] {
				continue
			}
			out = append(out, ent)
		}
		return out
	}
	model := prune(msPool)
	pspace := DedupeByHandle(model, prune(psPool))
	blocks := make(map[uint64][]any, len(kept))
	for h := range kept {
		blocks[h] = prune(filteredBlocks[h])
	}

	// 7. LAYER 表：0 层恒在 + 实际写出实体（含 POLYLINE 聚合顶点）引用
	// 到的图层，按句柄升序保证输出稳定；无实体图层表项不写出。
	verts := newDXFVertexIndex(doc)
	used := map[uint64]bool{}
	collect := func(list []any) {
		for _, ent := range list {
			b := entity.EntityBase(ent)
			if b == nil {
				continue
			}
			used[b.Layer] = true
			switch e := ent.(type) {
			case *entity.EntPolyline2d:
				for _, vh := range e.OwnedHandles {
					if v := verts.v2[vh]; v != nil {
						used[v.Layer] = true
					}
				}
			case *entity.EntPolyline3d:
				for _, vh := range e.OwnedHandles {
					if v := verts.v3[vh]; v != nil {
						used[v.Layer] = true
					}
				}
			case *entity.EntPolylinePface:
				for _, v := range verts.vp[e.Handle] {
					if b := entity.EntityBase(v); b != nil {
						used[b.Layer] = true
					}
				}
			case *entity.EntPolylineMesh:
				for _, vh := range e.OwnedHandles {
					if b := entity.EntityBase(verts.vpAll[vh]); b != nil {
						used[b.Layer] = true
					}
				}
			}
		}
	}
	collect(model)
	collect(pspace)
	for _, list := range blocks {
		collect(list)
	}
	layers := []dxfLayerRecord{{Handle: 0, Name: "0", Index: 7}}
	var handles []uint64
	for h := range used {
		if h != 0 {
			handles = append(handles, h)
		}
	}
	sort.Slice(handles, func(i, j int) bool { return handles[i] < handles[j] })
	for _, h := range handles {
		layers = append(layers, dxfLayerRecordFor(doc, h))
	}

	return &dxfFilterPlan{
		model:  model,
		pspace: pspace,
		blocks: blocks,
		layers: layers,
		verts:  verts,
	}, nil
}

// nameSet 名称切片 → 去空白集合。
func nameSet(names []string) map[string]bool {
	if len(names) == 0 {
		return map[string]bool{}
	}
	out := make(map[string]bool, len(names))
	for _, n := range names {
		out[strings.TrimSpace(n)] = true
	}
	return out
}

// dxfLayerRecordFor 构造单个图层句柄的 LAYER 表记录（与 dxfCollectLayers
// 的 add 逻辑同口径：真名/颜色取 LayerColors，缺失按句柄合成）。
func dxfLayerRecordFor(doc *Document, h uint64) dxfLayerRecord {
	rec := dxfLayerRecord{Handle: h, Name: docLayerName(doc, h), Index: 7}
	if lc, ok := doc.LayerColors[h]; ok {
		if lc.HasTrue {
			rec.TrueColor = lc.TrueColor & 0x00FFFFFF
		} else if lc.Index != 0 {
			rec.Index = int64(lc.Index)
		}
	}
	return rec
}
